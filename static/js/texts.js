/** Look up a text and fill in {placeholders}. t("errors.RATE_LIMITED", {seconds: 5}) */
export function t(path, vars = {}) {
  const value = path.split(".").reduce((obj, key) => (obj == null ? obj : obj[key]), TEXT);
  if (typeof value !== "string") return path;
  return value.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}
